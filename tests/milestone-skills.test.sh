#!/bin/zsh
# Planning + lane skills + docs know about milestones: literal asserts on the prose contract.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
source "$HERE/lib.sh"

# assert_lacks <haystack> <needle> <msg>
assert_lacks() { assert_eq "$([[ "$1" == *"$2"* ]] && echo present || echo absent)" absent "$3"; }

FORMAT="$(cat "$ROOT/.claude/skills/multiphase-plan/references/plan-format.md")"
PLAN_SKILL="$(cat "$ROOT/.claude/skills/multiphase-plan/SKILL.md")"
PICKUP="$(cat "$ROOT/.claude/skills/loop-pickup/SKILL.md")"
HANDOFF="$(cat "$ROOT/.claude/skills/loop-handoff/SKILL.md")"
PROTOCOL="$(cat "$ROOT/.claude/skills/loop-execute/references/loop-protocol.md")"
CLAUDE_MD="$(cat "$ROOT/CLAUDE.md")"
README="$(cat "$ROOT/loop-web/README.md")"

echo "milestone skills: plan-format documents the Approach grammar"
assert_contains "$FORMAT" '## Milestone N — <outcome>' "milestone section heading"
assert_contains "$FORMAT" 'a plain `## Phases` plan is one implicit milestone 1' "plain Phases = implicit milestone 1"
assert_contains "$FORMAT" '- **Integration branch (owner/repo):**' "per-repository branch line"
assert_contains "$FORMAT" '- **PR (owner/repo):**' "per-repository PR line"
assert_contains "$FORMAT" 'milestone repository line > milestone line > (milestone 1 only) `## Repositories` override > Loop config' "branch precedence"
assert_contains "$FORMAT" 'Milestones ≥2 must declare their branch' "M>=2 branch required"
assert_contains "$FORMAT" 'may not repeat for the same repository across milestones' "branch uniqueness"
assert_contains "$FORMAT" 'applies only to milestone-less plans' "Repositories PR line scope"
assert_contains "$FORMAT" '`[gate: merge]`' "gate tag"
assert_contains "$FORMAT" 'must list the gate in `Depends on` explicitly' "explicit gate deps"
assert_contains "$FORMAT" "A milestone's participants are the repositories of its work phases" "participants"
assert_contains "$FORMAT" '`awaiting merge`' "Status awaiting merge"
assert_contains "$FORMAT" '`…/<owner--repo>/integration-<branch-slug>-<hash8>`' "milestone >=2 worktree path"
assert_contains "$FORMAT" '`…/<owner--repo>/integration`' "milestone 1 worktree path"
assert_contains "$FORMAT" '## Milestone 1 — ' "two-milestone template: M1"
assert_contains "$FORMAT" '## Milestone 2 — ' "two-milestone template: M2"

echo "milestone skills: multiphase-plan proposes milestones sparingly"
assert_contains "$PLAN_SKILL" 'Propose milestones only when the effort is too big for one PR' "milestones only when too big"
assert_contains "$PLAN_SKILL" 'each milestone leaves main shippable' "each milestone shippable"
assert_contains "$PLAN_SKILL" '  - milestones: one PR, or several' "step-1 question gate asks about milestones"
assert_contains "$PLAN_SKILL" 'milestones ≥2 must declare their own integration branch; milestone 1 may fall back to Loop config' "only M>=2 must declare a branch"
assert_lacks "$PLAN_SKILL" 'every milestone declares its own integration branch' "no blanket per-milestone branch rule"

echo "milestone skills: loop-pickup respects the current milestone"
assert_contains "$PICKUP" 'never offer or claim a phase of a later milestone than `state.milestone`' "pickup never claims later milestone"
assert_contains "$PICKUP" 'REFUSED: phase belongs to a later milestone' "pickup auto refusal"
assert_contains "$PICKUP" '`GET /api/loops/<id>/plan` → `.milestone`' "pickup: no state.json → daemon milestone"
assert_contains "$PICKUP" 'lowest milestone whose gate phase is not `done`' "pickup: daemon-down fallback"
assert_contains "$PICKUP" 'plan `**Status:**` is `awaiting merge`, the current milestone is the one whose gate is the last `done` gate' "pickup: parked status pins current milestone"
assert_contains "$PICKUP" 'status is unclear, refuse every later-milestone claim' "pickup: unclear status refuses later claims"
assert_lacks "$PICKUP" 'absent = milestone 1' "pickup: no blind milestone-1 default"
assert_contains "$PICKUP" 'never claim a phase of an earlier (shipped) milestone' "pickup never claims earlier milestone"
assert_contains "$PICKUP" 'REFUSED: phase belongs to a shipped milestone' "pickup auto refusal: earlier milestone"

echo "milestone skills: loop-handoff never completes a later milestone"
assert_contains "$HANDOFF" 'never mark a phase of a later milestone than `state.milestone` `done`' "handoff never marks later milestone done"
assert_contains "$HANDOFF" '`GET /api/loops/<id>/plan` → `.milestone`' "handoff: no state.json → daemon milestone"
assert_contains "$HANDOFF" 'lowest milestone whose gate phase is not `done`' "handoff: daemon-down fallback"
assert_contains "$HANDOFF" 'plan `**Status:**` is `awaiting merge`, the current milestone is the one whose gate is the last `done` gate' "handoff: parked status pins current milestone"
assert_contains "$HANDOFF" 'status is unclear, promote nothing of a later milestone' "handoff: unclear status promotes nothing later"
assert_contains "$HANDOFF" 'never change the status of a phase of an earlier (shipped) milestone' "handoff never touches earlier milestone"

echo "milestone skills: loop-protocol milestone events carry their payload in detail"
assert_contains "$PROTOCOL" '| `milestone.awaiting-merge` | supervise (loop-state.sh log) | detail = `M<n> owner/repo=<url> …` |' "awaiting-merge detail"
assert_contains "$PROTOCOL" '| `milestone.resumed` | supervise (loop-state.sh log) | detail = `M<n>` |' "old-engine resumed detail"
assert_contains "$PROTOCOL" '| `milestone.resumed` | supervise (loop-state.sh log) | detail = `M<n> engine skills` |' "skills-engine resumed detail"
assert_lacks "$PROTOCOL" '| milestone, prs |' "no unsupported milestone/prs fields"

echo "milestone skills: shipped milestones are archived to stubs"
EXECUTE="$(cat "$ROOT/.claude/skills/loop-execute/SKILL.md")"
STUB_RULE='A phase that an `[archived]` stub lists is an existing phase with status `done`.'
assert_contains "$FORMAT" '### Archived milestones' "plan-format: archived milestones section"
assert_contains "$FORMAT" 'A plan keeps full phase blocks only for milestones that have not shipped.' "plan-format: only unshipped blocks"
assert_contains "$FORMAT" '## Milestone 1 — Backend ships behind a flag `[archived]`' "plan-format: stub heading marker"
assert_contains "$FORMAT" '- **Phases (all done):** 1, 2' "plan-format: stub phase list"
assert_contains "$FORMAT" '- **Gate:** Phase 2' "plan-format: stub gate"
assert_contains "$FORMAT" '- **Archive:** [milestones/m1.md](milestones/m1.md)' "plan-format: stub archive link"
assert_contains "$FORMAT" 'loop-plan.sh archive --milestone N' "plan-format: archive command"
assert_contains "$FORMAT" "$STUB_RULE" "plan-format: reader rule"
assert_contains "$PLAN_SKILL" 'A plan keeps full phase blocks only for milestones that have not shipped.' "multiphase-plan: only unshipped blocks"
assert_contains "$PLAN_SKILL" '`.loop/milestones/m<N>.md`' "multiphase-plan: archive location"
assert_contains "$EXECUTE" "$STUB_RULE" "loop-execute: preflight reader rule"
assert_contains "$EXECUTE" 'Never drop, reopen or renumber an archived phase.' "loop-execute: reconcile keeps archived phases"
assert_contains "$EXECUTE" 'loop-plan.sh archive --milestone <M> --dir .loop' "loop-execute: resume archives"
assert_contains "$PROTOCOL" 'milestones/m<N>.md' "loop-protocol: layout"
assert_contains "$PROTOCOL" 'loop-plan.sh archive --milestone <M> --dir .loop' "loop-protocol: resume archives"
assert_contains "$PICKUP" "$STUB_RULE" "loop-pickup: reader rule"
assert_contains "$HANDOFF" "$STUB_RULE" "loop-handoff: reader rule"
assert_contains "$HANDOFF" 'Never drop, reopen or renumber an archived phase.' "loop-handoff: reconcile keeps archived phases"
assert_contains "$CLAUDE_MD" 'loop-plan.sh archive' "CLAUDE.md: archive command"
assert_contains "$README" '`[archived]`' "README: archived stubs"

echo "milestone skills: one engine per plan and a switch at the merge gate"
PREFLIGHT="$(print -r -- "$EXECUTE" | sed -n '/^### 1\. Preflight$/,/^### 2\./p')"
RESUME="$(print -r -- "$EXECUTE" | sed -n '/^\*\*Milestone resume\*\*/,/^### Sub recycle/p')"
RESTART="$(print -r -- "$RESUME" | sed -n '/^5\. \*\*Restart\.\*\*/,/^6\. /p')"
assert_contains "$PREFLIGHT" 'engine: skills' "preflight reads the engine header"
assert_contains "$PREFLIGHT" 'Run `ws loop start <loop dir>`' "preflight starts the skills engine itself"
assert_contains "$PREFLIGHT" 'The human runs no command' "skills start needs no human command"
assert_contains "$PREFLIGHT" 'Never use the old engine as a fallback' "skills start never falls back to the old engine"
assert_contains "$PREFLIGHT" 'before repository checks, the lock or init' "skills start precedes old-engine side effects"
assert_contains "$RESUME" 'Steps 1–4 stay the same for both engines.' "switch preserves recovery, checks, archive, advance and apply"
assert_contains "$RESTART" 'ws loop create --dir' "restart creates or reuses the loop session"
assert_contains "$RESTART" 'loop-milestone.sh" open --dir' "restart uses the milestone producer"
assert_contains "$RESTART" 'loop.phases' "restart records phase facts with the tool"
assert_contains "$RESTART" 'loop.milestone' "restart records the current milestone with the tool"
assert_contains "$RESTART" 'loop.gate' "restart records earlier merged gates with the tool"
assert_contains "$RESTART" 'source: agent' "restart forbids agent-authored lifecycle facts"
assert_contains "$RESTART" 'Before `ws loop start <loop dir>`' "restart records the history before the start"
assert_contains "$RESTART" 'M<n> engine skills' "restart logs the selected engine"
assert_contains "$RESTART" 'in place of the orchestrator respawn' "skills start replaces the old-engine respawn"
assert_contains "$RESTART" "'.resumePending = null'" "restart still clears the crash marker"
assert_contains "$RESTART" 'Lessons in the seed.' "restart still seeds the lessons"
assert_contains "$RESTART" 'installed runtime' "skills switch uses the installed runtime"
assert_contains "$PROTOCOL" '### Engine switch and rollback' "protocol documents the engine switch"
assert_contains "$PROTOCOL" 'ws loop start <loop dir>' "protocol gives the skills command"
assert_contains "$PROTOCOL" 'M<n> engine skills' "protocol gives the resumed event detail"
assert_contains "$PROTOCOL" 'loop-milestone.sh resume --dir .loop' "protocol gives the recovery command"
assert_contains "$PROTOCOL" 'with `WS_LOOP_ID` unset' "recovery avoids the skills backend during the advance"
assert_contains "$PROTOCOL" 'removes `engine: skills` from the header while the loop is parked at a merge gate' "rollback changes the header only at a gate"
assert_contains "$PROTOCOL" '`loop-plan.sh push` and `/loop-execute resume`' "rollback pushes the header and resumes"
assert_contains "$PROTOCOL" '`ws loop pause`' "manual rescue pauses the skills loop"
assert_contains "$PROTOCOL" 'no child session of the loop runs' "manual rescue waits for child sessions"
assert_contains "$PROTOCOL" '`.loop/plan.md` and `.loop/state.json` agree with the merged work' "manual rescue reconciles durable state"

echo "milestone skills: retros go into the archive, and planners read their lessons"
FORMAT_FLAT="${(j: :)${=FORMAT}}"
PLAN_FLAT="${(j: :)${=PLAN_SKILL}}"
assert_contains "$FORMAT_FLAT" 'When `milestones/m<N>.retro.md` exists beside the plan, the archive file has the retro first, then `## Raw log`' "plan-format: retro first, then the raw log"
assert_contains "$FORMAT_FLAT" 'the Outcome bullet of the retro, else the milestone title' "plan-format: stub Outcome default"
assert_contains "$FORMAT_FLAT" 'An archived milestone with a pending retro file is not a no-op' "plan-format: attach to an archived milestone"
assert_contains "$PLAN_FLAT" 'read the `### Lessons` of the last 3 archive files' "multiphase-plan: reads recent lessons before it revises phases"
assert_contains "$CLAUDE_MD" 'loop-retro.mjs' "CLAUDE.md: loop-retro.mjs architecture row"
assert_contains "$CLAUDE_MD" 'node --test tests/loop-retro.test.mjs' "CLAUDE.md: loop-retro test command"

echo "milestone skills: output kinds and the accept gate"
assert_contains "$FORMAT" '`[output: pr|file|doc|output.md]`' "output tag"
assert_contains "$FORMAT" '`[gate: accept]`' "accept gate tag"
assert_contains "$FORMAT" '.loop/outputs/p<N>/' "non-PR output directory"
assert_contains "$FORMAT" 'For an output other than `pr`, `Verify:` is optional.' "Verify optional for non-PR output"
assert_contains "$PLAN_SKILL" '`[output: pr|file|doc|output.md]`' "planner chooses the output kind"
assert_contains "$PLAN_SKILL" 'one reviewer for `output.md`' "review follows the output kind"
echo "milestone skills: CLAUDE.md + README"
assert_contains "$CLAUDE_MD" '**Milestones:**' "CLAUDE.md milestones paragraph"
assert_contains "$CLAUDE_MD" '`awaiting-merge`' "CLAUDE.md awaiting-merge"
assert_contains "$CLAUDE_MD" '/loop-execute resume' "CLAUDE.md resume command"
assert_contains "$CLAUDE_MD" 'restart the Loop daemon (`awaiting-merge`' "CLAUDE.md daemon restart"
assert_contains "$CLAUDE_MD" 'launchctl kickstart -k gui/$(id -u)/com.rstagi.loop-web' "CLAUDE.md names the LaunchAgent label"
assert_contains "$CLAUDE_MD" 'only when no LaunchAgent is bound to :7717' "CLAUDE.md: loop-web.sh --daemon only without LaunchAgent"
assert_lacks "$CLAUDE_MD" '<loop-web LaunchAgent label>' "CLAUDE.md: no placeholder label"
assert_lacks "$CLAUDE_MD" 'restart the Loop daemon after upgrading' "CLAUDE.md: no redundant after upgrading"
assert_contains "$CLAUDE_MD" '`…/<owner--repo>/integration-<branch-slug>-<hash8>`' "CLAUDE.md: M>=2 worktree path"
assert_contains "$README" '### Milestones' "README milestones section"
assert_contains "$README" '`awaiting-merge`' "README awaiting-merge"
assert_contains "$README" 'restart the Loop daemon after upgrading' "README daemon restart"

test_summary
