#!/bin/zsh
# loop skill: prose contract for orchestration, explainers, checkpoints and installer.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
source "$HERE/lib.sh"
SKILL="$(cat "$ROOT/.claude/skills/loop/SKILL.md" 2>/dev/null)"

echo "loop skill: frontmatter"
assert_contains "$SKILL" 'name: loop' "frontmatter name"
assert_contains "$SKILL" 'description:' "frontmatter description"

echo "loop skill: start rule"
assert_contains "$SKILL" 'loop-milestone.sh open --dir <loop dir>' "starts with open"
assert_contains "$SKILL" 'ws loop get <loop> --json' "reads the loop"
assert_contains "$SKILL" 'first milestone that has open phases' "starts at the first open milestone"
assert_contains "$SKILL" 'milestone 7' "milestone 7 example"

echo "loop skill: spawn and wait"
assert_contains "$SKILL" '`depends_on`' "depends_on edges"
assert_contains "$SKILL" 'mode `any`' "multi-target wait"
assert_contains "$SKILL" 'loop-runner.sh --loop-dir <loop dir>' "runner records the result"
assert_contains "$SKILL" 'phase:<n>:attempt:<k>' "work attempt key"

echo "loop skill: lane rule"
assert_contains "$SKILL" 'loop-repo.sh lane' "lane worktree"
assert_contains "$SKILL" 'as `repo`' "lane worktree is the repo"
assert_contains "$SKILL" 'the printed `base`' "printed base"
assert_contains "$SKILL" 'A retry uses the same worktree.' "retry reuses the lane"

echo "loop skill: start rule for each output kind"
assert_contains "$SKILL" '`file`, `doc` or `output.md`' "non-pr kinds"
assert_contains "$SKILL" '<loop dir>/outputs/p<N>/' "outputs cwd"
assert_contains "$SKILL" 'no repository and no base' "no repo for non-pr"

echo "loop skill: action for each loop-merge.sh exit"
assert_contains "$SKILL" 'loop-merge.sh --worktree <integration worktree> --lane-branch <Suggested branch> --verify-cmd <Verify> --phase <N> --repository <slug> --run-id <loop id>' "merge command records loop.merge"
assert_contains "$SKILL" 'Start no other merge while a merge failure is open.' "one merge failure at a time"
assert_contains "$SKILL" '`[status: done]`' "done after exit 0"
assert_contains "$SKILL" 'loop-plan.sh push' "plan push after exit 0"
assert_contains "$SKILL" 'before you spawn a phase that depends on it' "push before dependents"
assert_contains "$SKILL" '--finish --verify-cmd' "exit 2 finish"
assert_contains "$SKILL" '<integration worktree> --abort' "exit 2 abort"
assert_contains "$SKILL" '<integration worktree> --undo' "exit 4 undo"
assert_contains "$SKILL" 'Exit 3' "exit 3 row"
assert_contains "$SKILL" 'Exit 1' "exit 1 row"

echo "loop skill: reviews and PRs"
assert_contains "$SKILL" '`merged` (output `pr`) or `done` (other outputs)' "review start rule"
assert_contains "$SKILL" 'gh pr create' "opens one PR per repository"
assert_contains "$SKILL" 'loop-review' "uses loop-review"

echo "loop skill: park rules"
assert_contains "$SKILL" 'loop-milestone.sh park --dir <loop dir> --milestone <N> --prs' "merge park"
assert_contains "$SKILL" 'loop-milestone.sh resume --dir <loop dir>' "resume command"
assert_contains "$SKILL" 'ws loop start <loop dir>' "start command"
assert_contains "$SKILL" 'Register no continuation.' "no continuation at a merge park"
assert_contains "$SKILL" 'loop-milestone.sh park --kind accept --phase <n> --artifacts' "accept park"
assert_contains "$SKILL" 'ws loop accept' "accept"
assert_contains "$SKILL" 'ws loop reject' "reject"

echo "loop skill: gate explainer"
GATE="${SKILL#*## Merge gate}"
GATE="${GATE%%## Accept gate*}"
assert_eq "$([[ "$GATE" == *'Run the gate explainer'*'loop-milestone.sh park'*'Notify the human'* ]] && echo yes)" yes "explainer precedes park and notification"
assert_contains "$GATE" 'explainer link or the failure' "gate notification includes explainer result"
EXPLAINERS="${SKILL#*## Milestone explainers}"
EXPLAINERS="${EXPLAINERS%%## Checks*}"
assert_contains "$EXPLAINERS" 'session_create' "explainer uses keyed create"
assert_contains "$EXPLAINERS" '`headless`, `key` and the `loop` object' "explainer belongs to the loop"
assert_contains "$EXPLAINERS" 'explainer:m<N>-ship' "stable gate key"
assert_contains "$EXPLAINERS" 'The same key returns the first session.' "no duplicate gate session"
assert_contains "$EXPLAINERS" '.loop/explainers/m<N>-ship/' "gate output directory"
assert_contains "$EXPLAINERS" '`props.json` and `narration.json`' "runner writes props and narration"
assert_contains "$EXPLAINERS" 'version 3' "walkthrough narration format"
assert_contains "$EXPLAINERS" 'Do not make a video.' "walkthrough replaces video"
assert_contains "$EXPLAINERS" 'render.mjs" --props <output dir>/props.json --narration <output dir>/narration.json' "renders the walkthrough"
assert_contains "$EXPLAINERS" 'shoot.mjs" --page <output dir>/index.html --out <output dir>/shots' "captures screenshots"
assert_contains "$EXPLAINERS" 'Artifact tool' "artifact publication"
assert_contains "$EXPLAINERS" 'absolute path of `index.html` to `link.txt`' "local publication fallback"
assert_contains "$EXPLAINERS" 'gh-media.mjs" --repo <owner/repo>' "GitHub media command"
assert_contains "$EXPLAINERS" '<!-- visual-explainer:m<N>-ship -->' "media comment marker"
assert_contains "$EXPLAINERS" 'each gate PR' "media on every gate PR"
assert_contains "$EXPLAINERS" 'edit that comment' "media comment is idempotent"
assert_contains "$EXPLAINERS" 'A failed explainer never blocks the park.' "failure preserves park"

echo "loop skill: retrospective"
assert_contains "$EXPLAINERS" 'ws loop get <loop> --json' "retro reads ws state"
assert_contains "$EXPLAINERS" 'ws log <loop> --type loop.' "retro reads the loop event prefix"
assert_eq "$([[ "$EXPLAINERS" != *'loop-retro.mjs'* ]] && echo yes)" yes "retro does not use the old-engine collector"
assert_contains "$EXPLAINERS" '.loop/milestones/m<N>.retro.md' "runner writes retro"
assert_contains "$EXPLAINERS" 'same facts' "page and retro share facts"
assert_contains "$EXPLAINERS" '`process` and `setbacks`' "page shows process costs"
for heading in '## Analysis and recap' '### Changes against the plan' '### Setbacks and hiccups' '### Lessons' '### Follow-ups'; do
  assert_contains "$EXPLAINERS" "$heading" "retro heading: $heading"
done
assert_contains "$EXPLAINERS" 'Cause: unknown' "no invented causes"
assert_contains "$EXPLAINERS" 'retro-error.txt' "missing retro is observable"

echo "loop skill: progress checkpoints"
CHECKPOINTS="${SKILL#*## Progress checkpoints}"
CHECKPOINTS="${CHECKPOINTS%%## Checks*}"
assert_contains "$CHECKPOINTS" '5 merged work phases since the last checkpoint' "phase-count trigger"
assert_contains "$CHECKPOINTS" '90 minutes' "time trigger"
assert_contains "$CHECKPOINTS" 'at least one merged work phase since the last checkpoint' "time trigger requires progress"
assert_contains "$CHECKPOINTS" 'whichever comes first' "either automatic trigger starts checkpoint"
assert_contains "$CHECKPOINTS" '.loop/control/checkpoint' "manual trigger"
assert_contains "$CHECKPOINTS" 'Remove `.loop/control/checkpoint` when the checkpoint starts.' "consumes manual trigger"
assert_contains "$CHECKPOINTS" 'skip the new checkpoint' "skips overlap"
assert_contains "$CHECKPOINTS" 'runner, render or publication still runs' "guards whole checkpoint lifecycle"
assert_contains "$CHECKPOINTS" 'in parallel with the phases' "parallel checkpoint"
assert_contains "$CHECKPOINTS" 'Never wait for a checkpoint before a phase, a merge or a gate.' "checkpoint cannot delay execution"
assert_contains "$CHECKPOINTS" 'Run this checkpoint pipeline as a detached task.' "render and publication cannot delay execution"
assert_contains "$CHECKPOINTS" 'checkpoints.json' "persists checkpoint counters"
assert_contains "$CHECKPOINTS" 'before the keyed create' "reserves checkpoint number before spawn"
assert_contains "$CHECKPOINTS" 'explainer:m<N>-cp<k>' "stable checkpoint key"
assert_contains "$CHECKPOINTS" '.loop/explainers/m<N>-cp<k>/' "unique checkpoint output"
assert_contains "$CHECKPOINTS" '`meta.checkpoint`' "checkpoint metadata"
assert_contains "$CHECKPOINTS" '{number: k, phasesDone, phasesTotal, since}' "checkpoint progress fields"
assert_contains "$CHECKPOINTS" '`pending`' "unmerged work stays pending"
assert_contains "$CHECKPOINTS" '`reviews` to an empty array' "no premature review verdict"
assert_contains "$CHECKPOINTS" 'no `findings` scene' "checkpoint narration omits findings"
assert_contains "$CHECKPOINTS" 'loop-notify.sh --level info --title "M<N> checkpoint <k>"' "checkpoint notification"
assert_contains "$CHECKPOINTS" 'with the link' "notification contains checkpoint link"

echo "loop skill: accept gate and finish"
ACCEPT="${SKILL#*## Accept gate}"
ACCEPT="${ACCEPT%%## Finish*}"
FINISH="${SKILL#*## Finish}"
FINISH="${FINISH%%## Milestone explainers*}"
assert_contains "$ACCEPT" 'An accept gate of the last milestone also runs the gate explainer' "accept gate of last milestone runs explainer"
assert_contains "$FINISH" 'The review of the last milestone has no gate.' "finish without a gate"
assert_contains "$FINISH" 'ws loop accept' "finish after accept"
assert_contains "$FINISH" 'Run the gate explainer' "finish runs explainer"
assert_contains "$FINISH" 'ws event loop.finish --source tool --target <loop> --key finish' "keyed loop.finish event"
assert_contains "$FINISH" 'show the loop as `finished`' "finished state"
assert_contains "$FINISH" 'loop-notify.sh' "finish notifies"
assert_contains "$FINISH" 'ws done --output handoff.md' "finish ends with done"
assert_contains "$FINISH" 'Register no continuation' "finish registers no continuation"

echo "loop skill: quota, checks and decisions"
assert_contains "$SKILL" 'ws usage --preflight --plan <loop dir>/plan.md' "quota preflight"
assert_contains "$SKILL" 'ws loop check <loop>' "check before a merge"
assert_contains "$SKILL" 'ws loop ack' "human acknowledgment"
assert_contains "$SKILL" '`loop.decision`' "decision events"

echo "loop skill: recycle rule"
assert_contains "$SKILL" 'ws on me exit --spawn' "exit trigger on me"
assert_contains "$SKILL" 'Never register the exit trigger on the loop session' "never on the loop session"
assert_contains "$SKILL" 'ws done --output handoff.md' "done with handoff"

echo "loop skill: installer shares the skill"
assert_contains "$(<"$ROOT/install-agent-skills.sh")" $'\n  loop\n' "SHARED_SKILLS lists loop"

test_summary
