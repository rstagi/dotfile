#!/bin/zsh
# loop-execute public review contract: tiered local adversarial rounds, fixes between rounds, one post.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
source "$HERE/lib.sh"

SKILL="$(cat "$ROOT/.claude/skills/loop-execute/SKILL.md")"
FIX_SKILL="$(cat "$ROOT/.claude/skills/pr-review-fix-all/SKILL.md")"
FIX_AGENT="$(cat "$ROOT/.claude/agents/pr-review-fixer.md")"
PROTOCOL="$(cat "$ROOT/.claude/skills/loop-execute/references/loop-protocol.md")"

echo "review workflow: tiered staged local reviews and remediation"
assert_contains "$SKILL" '`[review: shallow|medium|max]`' "reads the review tier from the phase tags"
assert_contains "$SKILL" '`loop-review.sh stages --tier <T> --rounds <N>`' "generates the run list"
assert_contains "$SKILL" '`--chain <chain> --review-tier <T>' "passes chain + tier to every run"
assert_contains "$SKILL" '**never posts or mutates GitHub**' "adversaries stay local"
assert_contains "$SKILL" 'shallow: none — it performs the' "shallow final reviews the code itself"
assert_contains "$PROTOCOL" '| `medium` (default) | Sol `xhigh` + Opus `xhigh` + Grok `xhigh` | Opus `medium` + Opus fixers | Opus `xhigh` |' "medium tier: one adversary per provider"
assert_contains "$PROTOCOL" '| `max` | Astra `ultra` + Fable `max` + Grok `xhigh` |' "max tier: one adversary per provider"
assert_contains "$PROTOCOL" '- report: <absolute review-adv-c report.md of round r>' "fix receives the grok report"
assert_contains "$SKILL" '`review-adv-c`' "loop workflow runs the grok adversary"
assert_contains "$FIX_SKILL" 'three in medium/max' "remediation reconciles three reports outside shallow"
assert_contains "$PROTOCOL" '| `shallow` | Opus `high` (one reviewer) | Sonnet `medium`, no subagents |' "shallow tier"
assert_contains "$PROTOCOL" 'Every round is local-only.' "all adversarial rounds stay off GitHub"
assert_contains "$SKILL" '`/pr-review-fix-all`' "loop workflow invokes the remediation skill"
assert_contains "$PROTOCOL" '`/pr-review-fix-all`' "protocol invokes the remediation skill"

echo "review workflow: remediation skill owns Opus delegation"
assert_eq "$([[ "$FIX_SKILL" == *'disable-model-invocation: true'* ]] && echo blocked || echo invocable)" "invocable" "headless fix runs can invoke the skill"
assert_contains "$FIX_SKILL" 'Write `RUN_DIR/remediation-plan.md`' "records reconciliation before fixes"
assert_contains "$FIX_SKILL" 'accepted, rejected, or duplicate' "disposes every finding"
assert_contains "$FIX_SKILL" 'maximum of 3 concurrent subagents' "bounds parallel remediation"
assert_contains "$FIX_SKILL" '**shallow:** apply the fix groups yourself' "shallow coordinator fixes without subagents"
assert_contains "$FIX_SKILL" '`model: opus` (the latest Opus)' "remediation subagents run the latest Opus"
assert_contains "$FIX_SKILL" 'Agent tool with the `pr-review-fixer` subagent' "spawns through the skill"
assert_contains "$FIX_AGENT" 'model: opus' "fixer agents run the latest Opus"
assert_contains "$FIX_AGENT" 'must not commit, push, or post to GitHub' "restricts fixer mutations"
assert_contains "$FIX_SKILL" 'overlapping files or dependencies serially' "serializes conflicting groups"
assert_contains "$FIX_SKILL" 'must not commit, push, or post to GitHub' "keeps mutations with coordinator"
assert_contains "$FIX_SKILL" 'Run the repository verification command' "coordinator verifies integrated fixes"
assert_contains "$FIX_SKILL" 'Commit logical fix groups and fast-forward push' "coordinator owns commits and push"

echo "review workflow: one severity-gated GitHub review"
assert_contains "$PROTOCOL" 'one or more `[blocker]` findings → `REQUEST_CHANGES`' "blockers request changes"
assert_contains "$PROTOCOL" 'one or more `[major]` findings → `COMMENT`' "majors produce comment review"
assert_contains "$PROTOCOL" 'otherwise → `APPROVE`' "clean major/blocker result approves"
assert_contains "$PROTOCOL" '<!-- loop-review:<runId>:p<N>:<owner--repo>:final -->' "final post is phase-idempotent"
assert_contains "$PROTOCOL" 'review-p<N>-<owner--repo>-a<k>' "review artifacts are phase-scoped"

echo "review workflow: milestones park at merge gates"
assert_contains "$SKILL" '**Milestones.**' "preflight validates milestone sections"
assert_contains "$SKILL" 'list that gate in `Depends on` **explicitly**' "preflight rejects a missing explicit gate dependency"
assert_contains "$SKILL" 'M≥2 branch names are checked by name only' "later milestones get no check/prepare at preflight"
assert_contains "$SKILL" 'set `state.milestone = 1`' "init starts at milestone 1"
assert_contains "$SKILL" 'milestone-1 participants only' "init prepares milestone-1 participants only"
assert_contains "$SKILL" 'schedules only phases of `state.milestone`' "SUB schedules only the current milestone"
assert_contains "$SKILL" 'one PR per milestone per participant' "PR per milestone per participant"
assert_contains "$SKILL" 'milestone'"'"'s `PR` bullet' "PR URL written to the milestone PR bullet"
assert_contains "$SKILL" 'On a `[gate: merge]` review, park instead of respawning' "gate review parks"
assert_contains "$SKILL" 'state.awaitingMerge {milestone, prs{slug:url}}' "parking persists awaitingMerge"
assert_contains "$SKILL" 'plan Status `awaiting merge`' "parking sets plan Status awaiting merge"
assert_contains "$SKILL" '`milestone.awaiting-merge`' "parking emits the typed event"
assert_contains "$SKILL" '`/loop-execute resume`' "parking notification names the resume command"
assert_contains "$SKILL" '**keep** `sub/REVIEW_READY`' "parking keeps REVIEW_READY"
assert_contains "$SKILL" 'never `finish`, never respawn' "parking neither finishes nor respawns"
assert_contains "$SKILL" 'does not respawn while `state.awaitingMerge` is set' "step 3b backstop skips respawn while parked"
assert_contains "$SKILL" 'writes `status.json{outcome:"blocked"}` and exits' "SUB seeing awaitingMerge blocks"
assert_contains "$PROTOCOL" '| `milestone.awaiting-merge` | supervise (loop-state.sh log) | milestone, prs |' "event table: awaiting-merge"
assert_contains "$PROTOCOL" '| `milestone.resumed` | supervise (loop-state.sh log) | milestone |' "event table: resumed"
assert_contains "$PROTOCOL" '"awaitingMerge": { "milestone": 1, "prs": { "owner/api": "<gate PR url>" } }' "state schema: awaitingMerge"
assert_contains "$PROTOCOL" '"milestone": 1,' "state schema: milestone"
assert_contains "$PROTOCOL" '"milestones": { "1": { "prs": { "owner/api": "<gate PR url>" } } }' "state schema: milestone PR history"
assert_contains "$PROTOCOL" '`…/<owner--repo>/integration-<branch-slug>`' "worktree path for milestones >= 2"
assert_contains "$PROTOCOL" 'a parked loop keeps `sub/REVIEW_READY`' "two-tier: parked loop keeps REVIEW_READY"
assert_contains "$PROTOCOL" '| Milestone gate (supervise, after the gate review aggregates) |' "backend mapping: parking"
assert_contains "$PROTOCOL" 'while `state.awaitingMerge` is set' "crash-resume: no respawn while parked"

test_summary
